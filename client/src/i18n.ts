export type TKey = keyof typeof en;
const dicts: Record<"fa" | "en", Dict> = { en, fa };

export function translate(
  lang: "fa" | "en",
  key: TKey,
  vars?: Record<string, string | number>,
): string {
  let s = dicts[lang][key] ?? en[key] ?? key;
  if (vars)
    for (const [k, v] of Object.entries(vars))
      s = s.replace(`{${k}}`, lang === "fa" ? toFaDigits(String(v)) : String(v));
  return s;
}

export function useT() {
  const lang = useApp((s) => s.lang);
  return (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export function toFaDigits(s: string) {
  return s.replace(/\d/g, (d) => "۰۱۲۳۴۵۶۷۸۹"[Number(d)]);
}

/** Maps an API error to a localized message. */
export function errorText(lang: "fa" | "en", err: unknown): string {
  const e = err as { code?: string; message?: string };
  const key = `err.${e?.code}` as TKey;
  if (e?.code && key in en) return translate(lang, key);
  return lang === "en" && e?.message ? e.message : translate(lang, "err.generic");
}
